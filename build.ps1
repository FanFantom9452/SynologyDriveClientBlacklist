# Bundles src/ into the single ASCII-only run.ps1 used by irm | iex.
# Run this after changing anything under src/ or blacklist.filter.

$ErrorActionPreference = 'Stop'

$modules = @(
    'src\Domain\FilterDocument.ps1'
    'src\Domain\RuleCatalog.ps1'
    'src\Application\UseCases.ps1'
    'src\Infrastructure\SynologyPorts.ps1'
    'src\Presentation\HttpServer.ps1'
    'src\Main.ps1'
)

function ConvertTo-Base64File {
    param([string]$RelativePath)
    return [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $PSScriptRoot $RelativePath)))
}

$web = ConvertTo-Base64File 'src\web\index.html'
$template = ConvertTo-Base64File 'blacklist.filter'

$bundle = New-Object System.Text.StringBuilder
[void]$bundle.AppendLine('# GENERATED by build.ps1 - edit src/ instead.')
[void]$bundle.AppendLine('& {')
foreach ($module in $modules) {
    [void]$bundle.AppendLine([IO.File]::ReadAllText((Join-Path $PSScriptRoot $module), [Text.Encoding]::UTF8))
}
[void]$bundle.AppendLine('function Get-EmbeddedAsset {')
[void]$bundle.AppendLine('    param([string]$Name)')
[void]$bundle.AppendLine("    `$data = @{ web = '$web'; template = '$template' }")
[void]$bundle.AppendLine('    return [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($data[$Name]))')
[void]$bundle.AppendLine('}')
[void]$bundle.AppendLine('Start-SynologyFilterTool')
[void]$bundle.AppendLine('}')

$text = $bundle.ToString()
if ($text -match '[^\x00-\x7F]') { throw 'run.ps1 must stay ASCII-only: remove non-ASCII text from the .ps1 modules.' }
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'run.ps1'), $text, [Text.Encoding]::ASCII)
Write-Output 'Built run.ps1'
